'## 큐란?

**큐**(Queue)는 한쪽 끝으로 데이터를 넣고, 반대쪽 끝으로 꺼내는 자료구조입니다. 넣는 쪽을 **rear**(뒤), 꺼내는 쪽을 **front**(앞)라고 부릅니다.

매표소 앞의 줄을 떠올리면 됩니다. 새로 온 사람은 줄 맨 뒤에 서고, 표는 맨 앞사람부터 삽니다. 새치기는 할 수 없습니다.

## 핵심 성질: FIFO

**FIFO**(First In, First Out, 선입선출) — 가장 먼저 들어온 데이터가 가장 먼저 나갑니다.

A, B, C 순서로 넣으면 A, B, C 순서 그대로 나옵니다. 스택과 달리 순서가 뒤집히지 않으므로, 도착한 순서대로 공평하게 처리해야 할 때 씁니다.

## 주요 연산

| 연산 | 하는 일 | 시간 |
| --- | --- | --- |
| Enqueue | 맨 뒤에 데이터를 넣는다 | O(1) |
| Dequeue | 맨 앞의 데이터를 꺼낸다 | O(1) |
| Peek | 맨 앞의 데이터를 꺼내지 않고 보기만 한다 | O(1) |
| isEmpty | 비어 있는지 확인한다 | O(1) |

넣는 곳(rear)과 꺼내는 곳(front)의 위치만 기억하면 되므로 모든 연산이 빠릅니다.

## 어떻게 만드나

- **원형 배열(원형 큐)**: 일반 배열에서 앞을 꺼내면 앞쪽 칸이 비어 낭비됩니다. 배열의 끝과 처음을 이어 붙인 것처럼 front·rear 인덱스를 돌려 쓰면 빈칸을 다시 활용할 수 있습니다.
- **연결 리스트**: 맨 뒤에 노드를 붙이고 맨 앞에서 뗍니다. 앞(head)과 뒤(tail)를 모두 기억해 두면 양쪽 다 O(1)입니다.

## 어디에 쓰이나

- **작업 대기열**: 프린터 출력, 서버로 들어온 요청을 들어온 순서대로 처리합니다.
- **운영체제 스케줄링**: 실행을 기다리는 프로세스들이 큐에 줄을 섭니다.
- **너비 우선 탐색(BFS)**: 가까운 곳부터 차례로 방문할 곳을 큐에 넣고 꺼냅니다.
- **버퍼**: 키보드 입력, 동영상 스트리밍처럼 받는 속도와 쓰는 속도가 다를 때 잠시 담아 둡니다.

## Java에서는

```java
Queue<Integer> queue = new ArrayDeque<>();
queue.offer(1);               // [1]        (Enqueue)
queue.offer(2);               // [1, 2]
int front = queue.peek();     // 1 (꺼내지 않음)
int out = queue.poll();       // 1, 남은 것: [2]  (Dequeue)
boolean empty = queue.isEmpty(); // false
```

