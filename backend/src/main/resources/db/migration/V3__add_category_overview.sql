'## 스택이란?

**스택**(Stack)은 데이터를 한쪽 끝에서만 넣고 뺄 수 있는 자료구조입니다. 데이터가 들어오고 나가는 그 끝을 **top**(맨 위)이라고 부릅니다.

책상 위에 쌓아 둔 책 더미를 떠올리면 됩니다. 새 책은 맨 위에 올리고, 책을 가져갈 때도 맨 위에서 가져갑니다. 맨 아래 책을 꺼내려면 그 위의 책을 모두 먼저 치워야 합니다.

## 핵심 성질: LIFO

**LIFO**(Last In, First Out, 후입선출) — 가장 나중에 들어온 데이터가 가장 먼저 나갑니다.

A, B, C 순서로 넣으면 C, B, A 순서로 나옵니다. 넣은 순서가 꺼낼 때 뒤집힌다는 점이 스택을 쓰는 이유이기도 합니다.

## 주요 연산

| 연산 | 하는 일 | 시간 |
| --- | --- | --- |
| Push | 맨 위에 데이터를 넣는다 | O(1) |
| Pop | 맨 위의 데이터를 꺼낸다 | O(1) |
| Peek | 맨 위의 데이터를 꺼내지 않고 보기만 한다 | O(1) |
| isEmpty | 비어 있는지 확인한다 | O(1) |

모든 연산이 top 한 곳에서만 일어나므로 데이터 개수와 상관없이 빠릅니다. 대신 중간에 있는 데이터를 바로 꺼낼 수는 없습니다.

## 어떻게 만드나

- **배열**: 마지막 칸의 위치(top 인덱스)만 기억하면 됩니다. 메모리가 붙어 있어 빠르지만, 크기가 고정이면 가득 찰 수 있습니다.
- **연결 리스트**: 새 노드를 맨 앞에 붙이고 맨 앞에서 뗍니다. 크기 제한이 없지만 노드마다 연결 정보가 더 듭니다.

## 어디에 쓰이나

- **함수 호출**: 함수가 호출될 때마다 실행 정보가 콜 스택에 쌓이고, 끝나면 빠집니다.
- **되돌리기(Ctrl+Z)**: 마지막에 한 작업부터 차례로 취소합니다.
- **브라우저 뒤로 가기**: 방금 본 페이지부터 거꾸로 돌아갑니다.
- **괄호 검사**: 여는 괄호를 쌓아 두었다가 닫는 괄호가 나오면 짝을 맞춰 꺼냅니다.

